#this is simple calculator with fixed operations

a = float(input("Enter a number: "))
b = float(input("Enter a number: "))

print("Addition: ", a + b)
print("Subtraction: ", a - b)
print("Multiplication: ", a * b)
print("Division: ", a / b)
print("Floor Division: ", a // b)
print("Modulo: ", a % b)
print("Exponent: ", a ** b)
'''here is a simple program to take a decimal number from 
    user and convert it to an integer
'''

#Take a decimal number from user
decimal_num = float(input("Enter a decimal number: "))

#Convert that into integer
integr_num=int(decimal_num)

#Print the integer number
print("The integer number is: ", integr_num)

#Convert that into Round value
round_num = round(decimal_num)

#Print the round value
print("The round value is: ", round_num)